/**
 * Keep the menu from echoing the shops' ALL-CAPS labels.
 */
export function spineShelfDisplay(shelf: LiveSpineShelf): string {
  const label = shelf.label.trim();
  if (!label || label !== label.toUpperCase() || !/[A-Z]/.test(label)) return label;
  return label
    .toLowerCase()
    .replace(/(^|[\s/()-])([a-z])/g, (_: string, sep: string, ch: string) => sep + ch.toUpperCase());
}

